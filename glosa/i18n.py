def t(key: str, lang: Lang) -> str:
    """The text for `key` in `lang`. Unknown keys raise KeyError on purpose."""
    return STRINGS[lang if lang in STRINGS else DEFAULT_LANG][key]


def admin_t(key: str, lang: Lang) -> str:
    """A panel text (``ADMIN_STRINGS``). Unknown keys raise KeyError."""
    return ADMIN_STRINGS[lang if lang in ADMIN_STRINGS else DEFAULT_LANG][key]


def admin_plural(key: str, n: int, lang: Lang) -> str:
    """The singular or plural form of a panel text ("a|b"), with {n} filled."""
    one, _, many = admin_t(key, lang).partition("|")
    return (one if n == 1 or not many else many).format(n=n)


# Ruling 63: the sticky per-visitor interface-language cookie, set by
# glosa/web/pages.py and glosa/web/admin_api.py's _set_lang_cookie() whenever
# ?lang= is used, and read back (before Settings.ui_language) on the next visit.
LANG_COOKIE = "glosa_lang"
LANG_COOKIE_MAX_AGE = 60 * 60 * 24 * 365  # 1 year


def resolve_ui_lang(
    *,
    query_lang: str | None,
    cookie_lang: str | None,
    configured: str,
    accept_language: str | None,
) -> tuple[Lang, Lang | None]:
    """(interface language, the one forced by ``?lang=`` or None).

    Ruling 63's precedence: ``?lang=`` always wins, and the caller makes
    that choice sticky (``LANG_COOKIE``, set from the returned "forced"
    value); else the sticky cookie from an earlier visit; else
    ``Settings.ui_language`` when it's "es" or "en" (Accept-Language is
    ignored); else -- ``configured`` is "auto", or there is no configured
    value at all -- today's Accept-Language detection (``detect_lang``).
    """
    forced = cast(Lang, query_lang) if query_lang in SUPPORTED else None
    if forced:
        return forced, forced
    if cookie_lang in SUPPORTED:
        return cast(Lang, cookie_lang), None
    if configured in SUPPORTED:
        return cast(Lang, configured), None
    return detect_lang(accept_language), None


def detect_lang(accept_language: str | None) -> Lang:
    """Pick "es" or "en" from an Accept-Language header, by q-value.

    Ties keep header order; q=0 and malformed q-values don't count.
    Anything else (no header, only other languages, "*") gives "es".
    """
    if not accept_language:
        return DEFAULT_LANG
    best: str | None = None
    best_q = 0.0
    for part in accept_language.split(","):
        tag, _, params = part.strip().partition(";")
        primary = tag.strip().lower().split("-", 1)[0]
        if primary not in SUPPORTED:
            continue
        q = _quality(params)
        if q > best_q:
            best, best_q = primary, q
    return cast(Lang, best) if best else DEFAULT_LANG


def _quality(params: str) -> float:
    for param in params.split(";"):
        name, _, value = param.strip().partition("=")
        if name.strip().lower() == "q":
            try:
                q = float(value)
            except ValueError:
                return 0.0
            return q if 0.0 <= q <= 1.0 else 0.0
    return 1.0


def lang_name(code: str, lang: Lang) -> str:
    """Name of language `code` as written in a `lang` sentence ("inglés")."""
    return LANG_NAMES.get(lang, LANG_NAMES[DEFAULT_LANG]).get(code, code.upper())


def endonym(code: str) -> str:
    """Name of language `code` in that language ("Español", "English")."""
    return ENDONYMS.get(code, code.upper())


def join_names(names: list[str], lang: Lang) -> str:
    """"A, B y C" / "A, B and C"."""
    if len(names) <= 1:
        return "".join(names)
    return f"{', '.join(names[:-1])} {t('and', lang)} {names[-1]}"
